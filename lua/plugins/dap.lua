return {
	specs = {
		"https://github.com/mfussenegger/nvim-dap",
		"https://github.com/rcarriga/nvim-dap-ui",
		"https://github.com/nvim-neotest/nvim-nio",
		"https://github.com/leoluz/nvim-dap-go",
	},
	setup = function()
		local dap = require("dap")
		local dapui = require("dapui")
		require("dap-go").setup()


		dapui.setup({
			icons = { expanded = "▼", collapsed = "▶", current_frame = "*" },
			controls = {
				icons = {
					pause = "||",
					play = "▶",
					step_into = "↓",
					step_over = "→",
					step_out = "↑",
					step_back = "←",
					run_last = "▶▶",
					terminate = "■",
					disconnect = "↗",
				},
			},
		})

		vim.api.nvim_set_hl(0, "DapBreak", { fg = "#e51400" })
		vim.api.nvim_set_hl(0, "DapStop", { fg = "#ffcc00" })
		local breakpoint_icons = {
			Breakpoint = "•",
			BreakpointCondition = "?",
			BreakpointRejected = "!",
			LogPoint = "◊",
			Stopped = "▶",
		}
		for type, icon in pairs(breakpoint_icons) do
			local tp = "Dap" .. type
			local hl = type == "Stopped" and "DapStop" or "DapBreak"
			vim.fn.sign_define(tp, { text = icon, texthl = hl, numhl = hl })
		end

		dap.listeners.after.event_initialized["dapui_config"] = dapui.open
		dap.listeners.before.event_terminated["dapui_config"] = dapui.close
		dap.listeners.before.event_exited["dapui_config"] = dapui.close


		vim.keymap.set("n", "<F5>", dap.continue, { desc = "Debug: Start/Continue" })
		vim.keymap.set("n", "<F1>", dap.step_into, { desc = "Debug: Step Into" })
		vim.keymap.set("n", "<F2>", dap.step_over, { desc = "Debug: Step Over" })
		vim.keymap.set("n", "<F3>", dap.step_out, { desc = "Debug: Step Out" })
		vim.keymap.set("n", "<F7>", dapui.toggle, { desc = "Debug: Toggle UI" })

		vim.keymap.set("n", "<leader>Dc", dap.continue, { desc = "[D]ebug [C]ontinue" })
		vim.keymap.set("n", "<leader>Di", dap.step_into, { desc = "[D]ebug step [I]nto" })
		vim.keymap.set("n", "<leader>Do", dap.step_over, { desc = "[D]ebug step [O]ver" })
		vim.keymap.set("n", "<leader>DO", dap.step_out, { desc = "[D]ebug step [O]ut" })
		vim.keymap.set("n", "<leader>Dp", dap.pause, { desc = "[D]ebug [P]ause" })
		vim.keymap.set("n", "<leader>Dr", dap.repl.open, { desc = "[D]ebug [R]EPL" })
		vim.keymap.set("n", "<leader>Dl", dap.run_last, { desc = "[D]ebug run [L]ast" })
		vim.keymap.set("n", "<leader>Dt", dap.terminate, { desc = "[D]ebug [T]erminate" })
		vim.keymap.set("n", "<leader>Du", dapui.toggle, { desc = "[D]ebug toggle [U]I" })


		vim.keymap.set("n", "<leader>bb", dap.toggle_breakpoint, { desc = "[B]reakpoint toggle" })
		vim.keymap.set("n", "<leader>bB", function()
			dap.set_breakpoint(vim.fn.input("Breakpoint condition: "))
		end, { desc = "[B]reakpoint conditional" })
		vim.keymap.set("n", "<leader>bl", function()
			dap.set_breakpoint(nil, nil, vim.fn.input("Log point message: "))
		end, { desc = "[B]reakpoint [L]og point" })
	end,
}
